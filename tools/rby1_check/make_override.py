"""Write overrides/rby1_24dof.usda: restore the 24 body DOF on the lab's generated RB-Y1 USD.

The generated USDs (assets/generated/rby1_*.usd) bake an 18-DOF variant: wheels, torso and head
joints are PhysicsFixedJoint and `joints/fixed_base` pins the base to the world. Their limits and
drive attributes are still authored, so a stronger layer only has to re-type the joints, apply the
drive schema and deactivate `fixed_base`. It also moves ArticulationRootAPI onto the `base` rigid
body: on the non-rigid /RBY1 Xform PhysX chooses link_torso_5 as the floating-base root link.
The source files are untouched.

    python tools/rby1_check/make_override.py [--base rbgripper_d405_collision]
"""
from __future__ import annotations

import argparse

from common import TOOLS, USD_FILES

REVOLUTE = ["left_wheel", "right_wheel", "torso_0", "torso_1", "torso_2", "torso_3", "torso_4", "torso_5",
            "head_0", "head_1"]

ap = argparse.ArgumentParser()
ap.add_argument("--base", default="rbgripper_d405_collision", choices=list(USD_FILES))
ap.add_argument("--out", default=str(TOOLS / "overrides" / "rby1_24dof.usda"))
args = ap.parse_args()


def main():
    import os

    base = USD_FILES[args.base]
    rel = os.path.relpath(base, os.path.dirname(os.path.abspath(args.out)))
    joints = "\n".join(
        f'''        def PhysicsRevoluteJoint "{n}" (
            prepend apiSchemas = ["PhysicsDriveAPI:angular", "PhysicsJointStateAPI:angular"]
        )
        {{
        }}
''' for n in REVOLUTE)
    text = f'''#usda 1.0
(
    defaultPrim = "RBY1"
    metersPerUnit = 1
    upAxis = "Z"
    kilogramsPerUnit = 1
    doc = """RB-Y1 24-DOF override (generated by tools/rby1_check/make_override.py).
Re-types wheels/torso/head from FixedJoint to RevoluteJoint, frees the base and moves the
articulation root API from the /RBY1 Xform to the base link (otherwise PhysX picks link_torso_5
as the floating root).
Base layer: {base.name}"""
    subLayers = [
        @{rel}@
    ]
)

over "RBY1" (
    delete apiSchemas = ["PhysicsArticulationRootAPI", "PhysxArticulationAPI"]
)
{{
    over "base" (
        prepend apiSchemas = ["PhysicsArticulationRootAPI", "PhysxArticulationAPI"]
    )
    {{
        bool physxArticulation:enabledSelfCollisions = 0
    }}

    over "joints"
    {{
{joints}
        over "fixed_base" (
            active = false
        )
        {{
        }}
    }}
}}
'''
    from pathlib import Path

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
